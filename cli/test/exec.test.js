import { test } from 'node:test';
import assert from 'node:assert/strict';
import { existsSync, readFileSync } from 'node:fs';
import { join } from 'node:path';
import { runStep, writeInstallScript, existingTouches } from '../exec.js';
import { tmp, write } from './helpers.js';

function ctx(over = {}) {
  const asked = [];
  return {
    asked,
    project: tmp(), print: false, yes: false, tty: true, env: process.env,
    confirm: async (q) => { asked.push(q); return over.answer ?? true; },
    ...over,
  };
}

test('runs the commands and reports done', async () => {
  const c = ctx();
  const r = await runStep({ commands: ['touch a', 'touch b'] }, c);
  assert.equal(r.state, 'done');
  assert.ok(existsSync(join(c.project, 'a')) && existsSync(join(c.project, 'b')));
});

test('a failing command leaves the step pending', async () => {
  const r = await runStep({ commands: ['exit 4'] }, ctx());
  assert.equal(r.state, 'pending');
  assert.match(r.reason, /exit 4/);
});

test('--print runs nothing', async () => {
  const c = ctx({ print: true });
  const r = await runStep({ commands: ['touch a'] }, c);
  assert.equal(r.state, 'pending');
  assert.ok(!existsSync(join(c.project, 'a')));
});

test('missing prerequisite leaves the step pending', async () => {
  const r = await runStep({ commands: ['true'], requires: ['groma-no-such-tool'] }, ctx());
  assert.equal(r.state, 'pending');
  assert.match(r.reason, /groma-no-such-tool not found/);
});

test('an existing touched file makes it ask; no means pending', async () => {
  const c = ctx({ answer: false });
  write(c.project, 'skills-lock.json', '{}');
  const r = await runStep({ commands: ['touch a'], touches: ['skills-lock.json', '.agents/skills/x'] }, c);
  assert.equal(c.asked.length, 1);
  assert.match(c.asked[0], /skills-lock\.json/);
  assert.equal(r.state, 'pending');
  assert.ok(!existsSync(join(c.project, 'a')));
});

test('--yes answers no to the question without asking', async () => {
  const c = ctx({ yes: true });
  write(c.project, 'skills-lock.json', '{}');
  const r = await runStep({ commands: ['touch a'], touches: ['skills-lock.json'] }, c);
  assert.equal(c.asked.length, 0);
  assert.equal(r.state, 'pending');
  assert.match(r.reason, /skills-lock\.json exists/);
});

test('askAlways asks even without existing files; yes runs it', async () => {
  const c = ctx();
  const r = await runStep({ commands: ['touch a'], askAlways: true }, c);
  assert.equal(c.asked.length, 1);
  assert.equal(r.state, 'done');
});

test('interactive commands need a terminal and no --yes', async () => {
  assert.equal((await runStep({ commands: ['true'], interactive: true }, ctx({ tty: false }))).state, 'pending');
  assert.equal((await runStep({ commands: ['true'], interactive: true }, ctx({ yes: true }))).state, 'pending');
  assert.equal((await runStep({ commands: ['true'], interactive: true }, ctx())).state, 'done');
});

test('existingTouches matches folder prefixes with *', () => {
  const p = tmp();
  write(p, '.claude/skills/openspec-propose/SKILL.md');
  assert.deepEqual(existingTouches(p, ['.claude/skills/openspec-*', '.github/skills/openspec-*', 'openspec/']), ['.claude/skills/openspec-*']);
});

test('install script collects pending commands; an existing one is kept', () => {
  const p = tmp();
  const first = writeInstallScript(p, [{ label: 'ponytail', reason: 'r', commands: ['echo 1'] }], '2026-11-04');
  assert.equal(first, '.groma/install.sh');
  const text = readFileSync(join(p, first), 'utf8');
  assert.match(text, /^#!\/bin\/sh\n# Generated by groma on 2026-11-04\. Review, then run: sh \.groma\/install\.sh\nset -eu\n/);
  assert.match(text, /# ponytail: r\necho 1\n/);
  const second = writeInstallScript(p, [{ label: 'x', reason: 'r', commands: ['echo 2'] }], '2026-11-05');
  assert.equal(second, '.groma/install-2026-11-05.sh');
  assert.equal(readFileSync(join(p, first), 'utf8'), text);
});

test('no pending commands, no install script', () => {
  const p = tmp();
  assert.equal(writeInstallScript(p, [], '2026-11-04'), null);
  assert.ok(!existsSync(join(p, '.groma')));
});

test("a bare '*' ignores groma's own skill folders", () => {
  const p = tmp();
  write(p, '.claude/skills/groma-survey/SKILL.md');
  assert.deepEqual(existingTouches(p, ['.claude/skills/*']), []);
  write(p, '.claude/skills/brainstorming/SKILL.md');
  assert.deepEqual(existingTouches(p, ['.claude/skills/*']), ['.claude/skills/*']);
});
