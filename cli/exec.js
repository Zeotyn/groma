// Run installer commands under groma's rules: never overwrite flags, ask
// before touching existing files, hand over what cannot run to .groma/install.sh.
import { spawnSync } from 'node:child_process';
import { accessSync, constants, existsSync, mkdirSync, readdirSync, writeFileSync } from 'node:fs';
import { delimiter, dirname, join, basename } from 'node:path';

export function onPath(cmd, env) {
  return (env.PATH ?? '').split(delimiter).some((d) => {
    try { accessSync(join(d, cmd), constants.X_OK); return true; } catch { return false; }
  });
}

export function existingTouches(project, touches = []) {
  return touches.filter((t) => {
    if (!t.endsWith('*')) return existsSync(join(project, t));
    const dir = join(project, dirname(t));
    // a bare '*' means any entry except groma's own skill folders
    const prefix = basename(t).slice(0, -1);
    return existsSync(dir) && readdirSync(dir).some((n) => n.startsWith(prefix) && (prefix || !n.startsWith('groma')));
  });
}

// step: { commands, touches, askAlways, interactive, requires }
// ctx:  { project, print, yes, tty, env, confirm(question) }
export async function runStep(step, ctx) {
  const missing = (step.requires ?? []).filter((t) => !onPath(t, ctx.env));
  if (missing.length) return { state: 'pending', reason: `${missing.join(', ')} not found` };
  if (ctx.print) return { state: 'pending', reason: 'written by --print' };
  if (step.interactive && (!ctx.tty || ctx.yes)) return { state: 'pending', reason: 'needs a person at the terminal' };

  const existing = existingTouches(ctx.project, step.touches);
  if (existing.length || step.askAlways) {
    const why = existing.length ? `${existing.join(', ')} exists` : 'may install outside the project';
    if (ctx.yes || !ctx.tty) return { state: 'pending', reason: `${why}, not run without asking` };
    const ok = await ctx.confirm(`${step.commands.join(' && ')}\n  ${why}. Run it now?`);
    if (!ok) return { state: 'pending', reason: `${why}, declined` };
  }

  for (const cmd of step.commands) {
    const r = spawnSync(cmd, { shell: true, stdio: 'inherit', cwd: ctx.project, env: ctx.env });
    if (r.status !== 0) return { state: 'pending', reason: `failed (exit ${r.status ?? r.signal})` };
  }
  return { state: 'done' };
}

// entries: [{ label, reason, commands }]. Returns the written path or null.
export function writeInstallScript(project, entries, date) {
  if (!entries.length) return null;
  mkdirSync(join(project, '.groma'), { recursive: true });
  const rel = existsSync(join(project, '.groma/install.sh')) ? `.groma/install-${date}.sh` : '.groma/install.sh';
  const body = entries.map((e) => `# ${e.label}: ${e.reason}\n${e.commands.join('\n')}\n`).join('\n');
  writeFileSync(join(project, rel), `#!/bin/sh\n# Generated by groma on ${date}. Review, then run: sh ${rel}\nset -eu\n\n${body}`, { mode: 0o755 });
  return rel;
}
