// Materialize the groma skills into each agent's project skill folder.
// A file is groma's to replace only when .groma/generated.json lists it and
// its current hash still matches; everything else belongs to the user.
import { createHash } from 'node:crypto';
import { existsSync, lstatSync, mkdirSync, readFileSync, readdirSync, realpathSync, renameSync, rmdirSync, statSync, unlinkSync, writeFileSync, chmodSync } from 'node:fs';
import { join, dirname, basename } from 'node:path';
import { SKILLS_SRC } from './data.js';

export const GENERATED = '.groma/generated.json';

export const sha256 = (buf) => createHash('sha256').update(buf).digest('hex');

export function readGenerated(project) {
  const f = join(project, GENERATED);
  return existsSync(f) ? JSON.parse(readFileSync(f, 'utf8')) : { generatedBy: null, files: {} };
}

// [major, minor, patch, pre-release] of `groma@1.2.3-rc.1` or `1.2.3`.
const parts = (v) => {
  const [core, ...pre] = String(v ?? '').replace(/^groma@/, '').split('-');
  return [...[0, 1, 2].map((i) => parseInt(core.split('.')[i], 10) || 0), pre.join('-')];
};

// True when the copies were generated by a newer groma than `version`.
// A pre-release (1.2.3-rc.1) is older than its release (1.2.3).
export function newerThan(generatedBy, version) {
  if (!generatedBy) return false;
  const [a, b] = [parts(generatedBy), parts(version)];
  for (let i = 0; i < 3; i++) if (a[i] !== b[i]) return a[i] > b[i];
  if (a[3] === b[3]) return false;
  if (!a[3] || !b[3]) return !a[3];
  return a[3] > b[3];
}

// Refuse to replace copies of a newer groma with older ones. Returns a message or null.
export function downgrade(generated, version, allow) {
  if (allow || !newerThan(generated.generatedBy, version)) return null;
  return `${GENERATED} was written by ${generated.generatedBy}, which is newer than this groma (${version}): update groma first (npx groma-cli@latest). Only to go back to ${version} on purpose, pass --allow-downgrade`;
}

// The line replaces an existing `  generatedBy:` line of the frontmatter, else
// goes below the first `metadata:` key, else a new block goes before the closing `---`.
export function addGeneratedBy(text, tag) {
  const end = text.indexOf('\n---', 4);
  if (!text.startsWith('---\n') || end < 0) return text;
  const head = text.slice(0, end + 1);
  const old = /^ {2}generatedBy:.*\n/m.exec(head);
  if (old) return text.slice(0, old.index) + `  generatedBy: ${tag}\n` + text.slice(old.index + old[0].length);
  const m = /^metadata:[ \t]*\n/m.exec(head);
  if (m) return text.slice(0, m.index + m[0].length) + `  generatedBy: ${tag}\n` + text.slice(m.index + m[0].length);
  return `${head}metadata:\n  generatedBy: ${tag}\n${text.slice(end + 1)}`;
}

const isLink = (f) => { try { return lstatSync(f).isSymbolicLink(); } catch { return false; } };

// Where `rel` (or its deepest existing ancestor) really is, or null when that
// is not a folder inside the project: a link there leads out of the project.
function realInside(project, rel) {
  const root = realpathSync(project);
  let p = rel;
  while (!existsSync(join(project, p)) && !isLink(join(project, p))) {
    if (!p.includes('/')) return root;
    p = dirname(p);
  }
  try {
    const real = realpathSync(join(project, p));
    return statSync(real).isDirectory() && `${real}/`.startsWith(`${root}/`) ? real : null;
  } catch { return null; }
}

// The symbolic link at or above `path`, below the skills folder `dir`, or null.
function linkAbove(project, dir, path) {
  let p = dir;
  for (const seg of path.slice(dir.length + 1).split('/')) {
    p = `${p}/${seg}`;
    if (isLink(join(project, p))) return p;
  }
  return null;
}

function walk(dir, prefix = '') {
  return readdirSync(dir, { withFileTypes: true }).flatMap((e) =>
    e.isDirectory() ? walk(join(dir, e.name), `${prefix}${e.name}/`) : [`${prefix}${e.name}`]);
}

const hashOf = (project, rel) => sha256(readFileSync(join(project, rel)));

// Returns { writes: [{path, content, mode, kind}], edited, conflicts, removals, reasons, records, before }.
// `records` is the generated.json file map after applying the plan; `before`
// is the map to write before the first file is touched (see applySkills).
export function planSkills({ project, agents, data, generated, force = false }) {
  const tag = `groma@${data.version}`;
  const known = generated.files;
  const plan = { writes: [], edited: [], conflicts: [], removals: [], reasons: {}, records: {}, before: { generatedBy: generated.generatedBy, files: {} } };
  const skills = readdirSync(SKILLS_SRC, { withFileTypes: true }).filter((e) => e.isDirectory()).map((e) => e.name);
  const conflict = (p) => { if (!plan.conflicts.includes(p)) plan.conflicts.push(p); };

  // Skills folders that lead out of the project are never written into.
  const dirs = [];
  for (const agent of agents) {
    const dir = data.agents.agents[agent].skills_dir;
    if (dirs.includes(dir) || plan.conflicts.includes(dir)) continue;
    if (realInside(project, dir)) dirs.push(dir);
    else conflict(dir);
  }

  for (const base of dirs) {
    for (const skill of skills) {
      const dir = `${base}/${skill}`;
      if (!isLink(join(project, dir)) && existsSync(join(project, dir)) && !Object.keys(known).some((f) => f.startsWith(`${dir}/`))) {
        conflict(dir);
        continue;
      }
      for (const file of walk(join(SKILLS_SRC, skill))) {
        const src = join(SKILLS_SRC, skill, file);
        let content = readFileSync(src);
        if (file === 'SKILL.md') content = Buffer.from(addGeneratedBy(content.toString('utf8'), tag));
        const path = `${dir}/${file}`;
        const hash = sha256(content);
        const write = { path, content, mode: statSync(src).mode };
        const link = linkAbove(project, base, path);
        if (link) {
          // a symbolic link at or above the path: never written into
          conflict(link);
          if (path in known) plan.records[path] = known[path];
          continue;
        }
        if (!existsSync(join(project, path))) {
          plan.writes.push({ ...write, kind: 'create' });
        } else if (!(path in known)) {
          conflict(path);
          continue;
        } else if (hashOf(project, path) === hash) {
          // already the new content
        } else if (hashOf(project, path) !== known[path] && !force) {
          plan.edited.push(path);
          plan.records[path] = known[path];
          continue;
        } else if (hashOf(project, path) !== hash) {
          plan.writes.push({ ...write, kind: 'update' });
          plan.before.files[path] = known[path];
        }
        plan.records[path] = hash;
      }
    }
  }

  // Generated files groma no longer ships: a file a shipped skill dropped, or
  // a file of a skill listed in retired-skills.txt. A skill that is merely
  // absent from this source (an older groma) is never deleted. Only paths
  // inside a selected agent's groma* skill folders qualify; other records are
  // carried over, and so is everything behind a symbolic link.
  const retired = data.retired ?? [];
  const owner = (path) => {
    if (path.split('/').includes('..')) return null;
    const base = dirs.find((d) => path.startsWith(`${d}/`) && /^groma[^/]*\/./.test(path.slice(d.length + 1)));
    if (!base || linkAbove(project, base, path)) return null;
    const skill = path.slice(base.length + 1).split('/')[0];
    return skills.includes(skill) || retired.includes(skill) ? skill : null;
  };
  for (const [path, hash] of Object.entries(known)) {
    if (path in plan.records || !existsSync(join(project, path))) continue;
    const skill = owner(path);
    if (!skill) plan.records[path] = hash;
    else if (hashOf(project, path) === hash) {
      plan.removals.push(path);
      plan.reasons[path] = skills.includes(skill) ? `no longer part of ${skill}` : `${skill} is retired`;
      plan.before.files[path] = hash;
    } else { plan.edited.push(path); plan.records[path] = hash; }
  }
  plan.before.files = { ...plan.records, ...plan.before.files };
  return plan;
}

const sorted = (files) => Object.fromEntries(Object.entries(files).sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0)));
// byte order, not localeCompare: the same on every machine and equal to `LC_ALL=C sort` in materialize.sh
const writeGenerated = (project, generatedBy, files) => {
  mkdirSync(join(project, '.groma'), { recursive: true });
  writeFileSync(join(project, GENERATED), JSON.stringify({ generatedBy, files: sorted(files) }, null, 2) + '\n');
};

// generated.json is written before the first file is touched: planned creates
// at their new hash, updates and removals at their old one, under the old
// generatedBy. A run that dies midway leaves every file it wrote recorded, so
// the next run owns it. Each file is written beside its place and renamed.
export function applySkills(project, plan, version) {
  const changes = plan.writes.length + plan.removals.length;
  if (changes) writeGenerated(project, plan.before.generatedBy ?? `groma@${version}`, plan.before.files);
  for (const w of plan.writes) {
    const f = join(project, w.path);
    const tmp = join(dirname(f), `.groma-tmp-${basename(f)}`);
    mkdirSync(dirname(f), { recursive: true });
    writeFileSync(tmp, w.content);
    chmodSync(tmp, w.mode & 0o777);
    renameSync(tmp, f);
  }
  for (const path of plan.removals) {
    unlinkSync(join(project, path));
    // drop folders the removal left empty, up to the skill folder's parent
    for (let d = dirname(path); d.split('/').length > 2 && readdirSync(join(project, d)).length === 0; d = dirname(d)) {
      rmdirSync(join(project, d));
    }
  }
  writeGenerated(project, `groma@${version}`, plan.records);
}
