#!/bin/sh
# Fill the change lists in docs/roadmap.md.
#
# Usage: roadmap.sh [--root <project dir>] [--stdout]
#   --stdout prints the resulting file and writes nothing
#   --today <date> is accepted and ignored (older callers)
#
# docs/roadmap.md is hand-written: one section "## M<N>: <title>" per milestone
# with a "**Goal:**" line and a "**Release gate:**" checklist. This script
# replaces only the text between the marker lines
#   <!-- groma:changes m<N> -->
#   <!-- /groma:changes -->
# with a table of the changes of milestone N: name, active or archived, and for
# an active change the tasks done as of this run (archived: "-"). Every other
# byte of the file stays as it is: CRLF line ends are kept, also in the lines
# written, and a file without a final newline gets none. A section without
# markers gets none (check-conventions.sh reports it), and a missing
# docs/roadmap.md is not created: start one from templates/roadmap-section.md.
#
# A change belongs to milestone N when its name starts with m<N>-. A change
# listed in .groma/conventions-baseline.txt (old names) also belongs to it
# through a line "Milestone: m<NNN>" in its proposal.md. Old umbrella milestone
# changes (m003-v0-3) are not listed: the section replaces them.
#
# Output: summary<TAB>blocks=<n><TAB>changed=<0|1>; hints on stderr.
# Exit codes: 0, 1 a marker block is not closed (nothing written), 2 usage error.
set -eu

HERE=$(CDPATH='' cd -- "$(dirname -- "$0")" && pwd)
# shellcheck source=SCRIPTDIR/lib-changes.sh
. "$HERE/lib-changes.sh"

ROOT=.
STDOUT=0
while [ $# -gt 0 ]; do
  case "$1" in
    --root) ROOT=$2; shift 2 ;;
    --today) shift 2 ;;
    --stdout) STDOUT=1; shift ;;
    *) echo "unknown argument: $1" >&2; exit 2 ;;
  esac
done

TAB=$(printf '\t')
TARGET="$ROOT/docs/roadmap.md"
if [ ! -f "$TARGET" ]; then
  echo "no docs/roadmap.md: write one from templates/roadmap-section.md when the first milestone is planned" >&2
  printf 'summary\tblocks=0\tchanged=0\n'
  exit 0
fi

blocks=$(awk "$ROADMAP_AWK"'marker_open($0) != "" { n++ } END { print n + 0 }' "$TARGET")
if [ "$blocks" -eq 0 ]; then
  if grep -q '^generated_by: groma roadmap.sh' "$TARGET"; then
    echo "docs/roadmap.md was generated by an older groma and has no marker blocks: replace its sections with the output of check-conventions.sh --suggest-migration" >&2
  else
    echo "docs/roadmap.md has no marker blocks: nothing to fill" >&2
  fi
fi

# one line per milestone change: <N><TAB><name><TAB><active|archived><TAB><done>/<total>
rows() {
  list_changes "$(changes_dir "$ROOT")" | sort | while IFS="$TAB" read -r name loc path; do
    [ -n "$name" ] || continue
    if is_umbrella "$name"; then continue; fi
    ms=$(milestone_of "$name")
    if [ -z "$ms" ] && [ -f "$path/proposal.md" ] && in_baseline "$name"; then
      ms=$(sed -nE 's/^Milestone:[[:space:]]*m0*([0-9]+).*/\1/p' "$path/proposal.md" | head -n 1)
    fi
    [ -n "$ms" ] || continue
    state=active; [ "$loc" = active ] || state=archived
    tasks="-"
    if [ "$loc" = active ] && [ -f "$path/tasks.md" ]; then
      total=$(grep -c '^[[:space:]]*- \[[ xX]\]' "$path/tasks.md" || true)
      done_n=$(grep -c '^[[:space:]]*- \[[xX]\]' "$path/tasks.md" || true)
      tasks="$done_n/$total"
    fi
    printf '%s\t%s\t%s\t%s\n' "$ms" "$name" "$state" "$tasks"
  done
}

render() {
  rows | awk -F "$TAB" "$ROADMAP_AWK"'
    pass == 1 { if ($1 != "") { n[$1]++; row[$1, n[$1]] = "| `" $2 "` | " $3 " | " $4 " |" } next }
    inb { if (marker_close($0)) { inb = 0; print } next }
    (k = marker_open($0)) != "" {
      print
      eol = ($0 ~ /\r$/) ? "\r" : ""          # written lines end like the marker line
      if (n[k] > 0) {
        print "| Change | State | Tasks |" eol; print "|---|---|---|" eol
        for (i = 1; i <= n[k]; i++) print row[k, i] eol
      } else print "No changes yet." eol
      inb = 1; next
    }
    { print }
    END { if (inb) exit 3 }' pass=1 - pass=2 "$TARGET"
}

TMP="$TARGET.groma.$$"
if [ "$STDOUT" -eq 1 ]; then TMP="${TMPDIR:-/tmp}/groma-roadmap.$$"; fi
if ! render > "$TMP"; then
  rm -f "$TMP"
  echo "docs/roadmap.md: a marker block has no closing line <!-- /groma:changes -->; nothing written" >&2
  exit 1
fi
# awk ends every line with a newline: take the last one away when the file has none
if [ -n "$(tail -c 1 "$TARGET")" ]; then
  awk 'NR > 1 { printf "\n" } { printf "%s", $0 }' "$TMP" > "$TMP.2" && mv "$TMP.2" "$TMP"
fi
if [ "$STDOUT" -eq 1 ]; then
  cat "$TMP"; rm -f "$TMP"
  exit 0
fi
changed=0
if ! cmp -s "$TMP" "$TARGET"; then
  cat "$TMP" > "$TARGET"
  changed=1
fi
rm -f "$TMP"
printf 'summary\tblocks=%s\tchanged=%s\n' "$blocks" "$changed"
